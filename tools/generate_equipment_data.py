#!/usr/bin/env python3
"""Generate the native equipment catalog from equipment_catalog.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def c_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
    )
    return f'"{escaped}"'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("catalog", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    category_keys = [entry["key"] for entry in catalog["categories"]]
    category_bits = {key: index for index, key in enumerate(category_keys)}
    series_order = catalog["series_order"]
    series_index = {
        series: index for index, series in enumerate(series_order)
    }
    items = sorted(catalog["items"].values(), key=lambda item: item["id"])

    lines = [
        "// Generated by tools/generate_equipment_data.py. Do not edit manually.",
        "static constexpr EquipmentInventoryDefinition kEquipmentInventoryDefinitions[] = {",
    ]
    for item in items:
        mask = 0
        for category in item.get("categories", []):
            if category not in category_bits:
                raise ValueError(f"Unknown category {category!r} in {item['id']}")
            mask |= 1 << category_bits[category]
        occupancy = item["occupancy"]
        series = item.get("series")
        if series not in series_index:
            raise ValueError(f"Unknown series {series!r} in {item['id']}")
        lines.append(
            "    { "
            f"{c_string(item['id'])}, "
            f"{c_string(item['name'])}, "
            f"{int(occupancy['width'])}, "
            f"{int(occupancy['height'])}, "
            f"0x{mask:03x}u, "
            f"{series_index[series]} "
            "},"
        )
    lines.extend(
        [
            "};",
            "",
            "constexpr int kEquipmentInventoryDefinitionCount =",
            "    static_cast<int>(sizeof(kEquipmentInventoryDefinitions) /",
            "                     sizeof(kEquipmentInventoryDefinitions[0]));",
            "",
            "static constexpr const char* kEquipmentSeriesNames[] = {",
        ]
    )
    lines.extend(
        f"    {c_string(series)}," for series in series_order
    )
    lines.extend(
        [
            "};",
            "",
            "constexpr int kEquipmentSeriesCount =",
            "    static_cast<int>(sizeof(kEquipmentSeriesNames) /",
            "                     sizeof(kEquipmentSeriesNames[0]));",
            "",
        ]
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
